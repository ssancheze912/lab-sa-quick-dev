import { test, expect } from '@playwright/test';

const FRONTEND_BASE_URL = 'http://localhost:5173';

// ─────────────────────────────────────────────────────────────────────────────
// Content negotiation and HTTP response headers
// ─────────────────────────────────────────────────────────────────────────────

test.describe('[P1] Frontend — HTTP response quality and content type', () => {
  test('[P1] should serve index.html with text/html content-type on root path', async ({
    request,
  }) => {
    // GIVEN: Vite dev server is running on port 5173
    // WHEN: A GET request is made to the root path
    const response = await request.get(FRONTEND_BASE_URL + '/');

    // THEN: Content-Type header indicates HTML document
    const contentType = response.headers()['content-type'] ?? '';
    expect(contentType).toContain('text/html');
  });

  test('[P1] should include a valid charset declaration in HTML content-type', async ({
    request,
  }) => {
    // GIVEN: Vite generates index.html with UTF-8 content
    // WHEN: The root path is requested
    const response = await request.get(FRONTEND_BASE_URL + '/');

    // THEN: Content-Type declares UTF-8 charset (required for i18n — Spanish UI)
    const contentType = response.headers()['content-type'] ?? '';
    expect(contentType.toLowerCase()).toContain('utf-8');
  });

  test('[P1] should return HTTP 200 for root path (not redirect to /index.html)', async ({
    request,
  }) => {
    // GIVEN: Vite serves a single-page application
    // WHEN: The root URL is accessed directly
    const response = await request.get(FRONTEND_BASE_URL + '/');

    // THEN: Response is 200, not a redirect — SPA root must be served directly
    expect(response.status()).toBe(200);
  });

  test('[P2] should return HTTP 200 for unknown SPA sub-routes (client-side routing)', async ({
    request,
  }) => {
    // GIVEN: TanStack Router handles routing client-side
    // WHEN: A request is made to an unknown route like /some-spa-route
    const response = await request.get(FRONTEND_BASE_URL + '/some-nonexistent-spa-route');

    // THEN: Vite dev server returns the index.html (200) — not 404 — to allow client routing
    // Note: Vite in dev mode serves index.html for non-asset paths (SPA fallback)
    expect(response.status()).toBe(200);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// React DOM and application root edge cases
// ─────────────────────────────────────────────────────────────────────────────

test.describe('[P1] Frontend — React mount and DOM structure', () => {
  test('[P1] should have exactly one root mount point in the HTML document', async ({ page }) => {
    // GIVEN: main.tsx calls createRoot(document.getElementById("root")!)
    // WHEN: The page loads
    await page.goto('/');

    // THEN: There is exactly one #root element (no duplicate mount points)
    const rootCount = await page.locator('#root').count();
    expect(rootCount).toBe(1);
  });

  test('[P1] should not render an empty #root element after hydration', async ({ page }) => {
    // GIVEN: React renders the RouterProvider and QueryProvider inside #root
    // WHEN: The app is fully loaded
    await page.goto('/');
    await page.waitForLoadState('networkidle');

    // THEN: #root has inner content (React mounted successfully, not blank)
    const rootInnerHTML = await page.locator('#root').innerHTML();
    expect(rootInnerHTML.trim()).not.toBe('');
  });

  test('[P1] should have lang attribute on <html> element for accessibility', async ({ page }) => {
    // GIVEN: index.html is generated by Vite
    // WHEN: The page loads
    await page.goto('/');

    // THEN: The <html> element has a lang attribute (required by WCAG 3.1.1)
    // index.html has lang="en" — acceptable for initial scaffold
    const lang = await page.locator('html').getAttribute('lang');
    expect(lang).toBeTruthy();
  });

  test('[P2] should have a viewport meta tag for mobile responsiveness', async ({ page }) => {
    // GIVEN: The app will serve mobile users (Pixel 5 in test matrix)
    // WHEN: The page loads
    await page.goto('/');

    // THEN: A viewport meta tag is present (required for responsive layouts)
    const viewportMeta = page.locator('meta[name="viewport"]');
    await expect(viewportMeta).toHaveCount(1);
  });

  test('[P2] should include the main JavaScript bundle in the HTML document', async ({ page }) => {
    // GIVEN: Vite injects the <script type="module" src="/src/main.tsx"> tag
    // WHEN: The page loads
    await page.goto('/');

    // THEN: A module script tag is present pointing to the app entry point
    const scriptTag = page.locator('script[type="module"]');
    await expect(scriptTag).toHaveCount(1);
  });
});

