test.describe('[P2] Frontend — Load performance boundaries', () => {
  test('[P2] should complete initial HTML load within 5 seconds', async ({ page }) => {
    // GIVEN: The Vite dev server is running (warm, not cold start)
    // WHEN: A navigation is initiated
    const startTime = Date.now();
    await page.goto('/');
    await page.waitForLoadState('domcontentloaded');
    const loadTime = Date.now() - startTime;

    // THEN: DOM content loads within 5 000 ms (dev server, not production)
    expect(loadTime).toBeLessThan(5000);
  });

  test('[P2] should complete full network idle within 15 seconds on initial load', async ({
    page,
  }) => {
    // GIVEN: Vite with HMR and module bundling may trigger multiple network requests
    // WHEN: The app loads all its assets
    const startTime = Date.now();
    await page.goto('/');
    await page.waitForLoadState('networkidle');
    const loadTime = Date.now() - startTime;

    // THEN: All network activity settles within 15 000 ms in dev mode
    expect(loadTime).toBeLessThan(15000);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// Stability — server handles concurrent and repeated requests
// ─────────────────────────────────────────────────────────────────────────────

test.describe('[P2] Frontend — Server stability under repeated requests', () => {
  test('[P2] should serve identical HTTP 200 responses on three consecutive loads', async ({
    request,
  }) => {
    // GIVEN: The Vite dev server is stateless for GET / requests
    // WHEN: Three consecutive GET / requests are made
    const responses = await Promise.all([
      request.get(FRONTEND_BASE_URL + '/'),
      request.get(FRONTEND_BASE_URL + '/'),
      request.get(FRONTEND_BASE_URL + '/'),
    ]);

    // THEN: All three responses return HTTP 200 (no transient failures)
    for (const response of responses) {
      expect(response.status()).toBe(200);
    }
  });

  test('[P2] should not accumulate console errors across two navigations to the same page', async ({
    page,
  }) => {
    // GIVEN: React and TanStack Router are properly initialized
    // WHEN: The user navigates to the root route twice (simulates browser back/forward)
    const consoleErrors: string[] = [];
    page.on('console', (msg) => {
      if (msg.type() === 'error') consoleErrors.push(msg.text());
    });

    await page.goto('/');
    await page.waitForLoadState('networkidle');
    await page.reload();
    await page.waitForLoadState('networkidle');

    // THEN: No console errors accumulate from duplicate React mounts or router re-initialization
    expect(consoleErrors).toHaveLength(0);
  });
});

